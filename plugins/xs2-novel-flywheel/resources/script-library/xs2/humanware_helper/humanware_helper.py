#!/usr/bin/env python3
"""Humanware helper: character voice generation, scoring and dialogue checks.

File-only, deterministic rule engine (no model calls). Consumed by the xs2
``/api/humanware/*`` routes through a JSON-over-stdout contract:

- Successful operations print one JSON object to stdout and exit 0.
- *Business* failures (e.g. missing profiles, unknown character) also exit 0
  and print ``{"status": "error", "message": ..., "code": <int>}``; the route
  forwards ``code`` as the HTTP status.
- Only process-level failures (bad args, IO crashes) exit non-zero; the route
  maps those to HTTP 500 with the stderr text.

Contract reference: xs2/docs/humanware-helper-contract.md
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

# --------------------------------------------------------------------------- IO

def _json(result: dict[str, Any]) -> None:
    sys.stdout.write(json.dumps(result, ensure_ascii=False) + "\n")


def _fail(code: int, message: str) -> None:
    _json({"status": "error", "message": message, "code": code})


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    # Deterministic bytes on every platform (no CRLF translation).
    path.write_text(content, encoding="utf-8", newline="\n")


def _resolve_in(root: Path, relative: str) -> Path:
    candidate = (root / relative).resolve()
    root_resolved = root.resolve()
    if candidate != root_resolved and root_resolved not in candidate.parents:
        raise ValueError("path escapes workspace root")
    return candidate


# ------------------------------------------------------------------ text helpers

_SENTENCE_SPLIT = re.compile(r"[^。！？!?；;\n]+[。！？!?；;\n]?")


def _sentences(text: str) -> list[str]:
    parts = [p.strip() for p in _SENTENCE_SPLIT.findall(text)]
    return [p for p in parts if len(p) >= 2]


def _avg_sentence_length(text: str) -> float:
    sentences = _sentences(text)
    if not sentences:
        return 0.0
    return sum(len(s) for s in sentences) / len(sentences)


def _ratio(text: str, pattern: re.Pattern[str]) -> float:
    sentences = _sentences(text)
    if not sentences:
        return 0.0
    return sum(1 for s in sentences if pattern.search(s)) / len(sentences)


QUESTION_RE = re.compile(r"[?？]|吗|呢|么|嘛$")
EXCLAMATION_RE = re.compile(r"[!！]|啊|呀|哇|啦$")


def _quote_texts(text: str) -> list[str]:
    """Extract dialogue from common Chinese quote pairs and ASCII quotes."""
    matches = re.findall(r"[“\"「]([^”\"」]*)[”\"」]", text)
    return [m.strip() for m in matches if m.strip()]


def _cjk_length(text: str) -> int:
    return len(re.sub(r"\s", "", text))


# ------------------------------------------------------------ voice definition

_VOICE_HEADING = "# 角色声音锚点"
_SECTION_MARKERS = ("###", "##")


def _parse_voice(text: str) -> dict[str, dict[str, Any]]:
    """Parse meta/character_voice.md into per-character anchors.

    Layout generated by this helper:

        # 角色声音锚点

        ## 角色名

        ### 核心声音定位
        - **表达方式**: ...

        ### 句法指纹
        - **平均句长**: 12
        - **问句倾向**: 0.20
        - **叹句倾向**: 0.10

        ### 口头禅
        - 用词: 罢了; 原来如此

        ### 绝不使用
        - 用词: 傻瓜

        ### 认知模式
        - 说明: ...
    """
    anchors: dict[str, dict[str, Any]] = {}
    current: str | None = None
    section: str | None = None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            current = stripped[3:].strip()
            anchors[current] = {
                "style": "",
                "avg_sentence_length": 0.0,
                "question_ratio": 0.0,
                "exclamation_ratio": 0.0,
                "tone_words": [],
                "banned_words": [],
                "cognition": "",
            }
            section = None
        elif current and stripped.startswith("### "):
            section = stripped[4:].strip()
        elif current and section and stripped.startswith("- "):
            body = stripped[2:].strip()
            key, _, value = body.partition(":")
            key = key.strip().strip("*").strip()
            value = value.strip()
            if section == "句法指纹":
                if "平均句长" in key:
                    anchors[current]["avg_sentence_length"] = _float_or_zero(value)
                elif "问句倾向" in key:
                    anchors[current]["question_ratio"] = _float_or_zero(value)
                elif "叹句倾向" in key:
                    anchors[current]["exclamation_ratio"] = _float_or_zero(value)
            elif section == "核心声音定位" and "表达方式" in key:
                anchors[current]["style"] = value
            elif section in ("口头禅", "绝不使用"):
                words = [w.strip() for w in re.split(r"[;；,，]", value) if w.strip()]
                if section == "口头禅":
                    anchors[current]["tone_words"].extend(words)
                else:
                    anchors[current]["banned_words"].extend(words)
            elif section == "认知模式":
                anchors[current]["cognition"] = value
    return anchors


def _float_or_zero(value: str) -> float:
    match = re.search(r"-?\d+(?:\.\d+)?", value)
    return float(match.group(0)) if match else 0.0


def _voice_template(character: str, hint: str = "") -> str:
    style = hint or "自然表达，符合人物身份与当下情绪"
    return (
        f"## {character}\n\n"
        f"### 核心声音定位\n"
        f"- **表达方式**: {style}\n\n"
        f"### 句法指纹\n"
        f"- **平均句长**: 14\n"
        f"- **问句倾向**: 0.15\n"
        f"- **叹句倾向**: 0.10\n\n"
        f"### 口头禅\n"
        f"- 用词: \n\n"
        f"### 绝不使用\n"
        f"- 用词: \n\n"
        f"### 认知模式\n"
        f"- 说明: 待补充\n"
    )


# ---------------------------------------------------------------- generate-voice

def _character_names_from_profiles(text: str) -> list[str]:
    names: list[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## ") and not stripped.startswith("### "):
            name = stripped[3:].strip()
            if name:
                names.append(name)
    return names


def cmd_generate_voice(root: Path) -> None:
    profiles = root / "meta" / "character_profiles.md"
    if not profiles.is_file():
        _fail(409, "character_profiles.md 不存在，请先创建角色档案")
        return
    text = _read(profiles)
    names = _character_names_from_profiles(text)
    if not names:
        _fail(409, "character_profiles.md 中没有可识别的角色条目（请用 ## 角色名 开头）")
        return
    style_hints = _style_hints_from_profiles(text)
    blocks = [_voice_template(name, style_hints.get(name, "")) for name in names]
    document = _VOICE_HEADING + "\n\n" + "\n".join(blocks)
    _write(root / "meta" / "character_voice.md", document)
    _json({
        "status": "success",
        "message": f"已生成 {len(names)} 个角色声音模板",
        "character_count": len(names),
    })


def _style_hints_from_profiles(text: str) -> dict[str, str]:
    """Best-effort: read the profile paragraph for speech-style keywords."""
    hints: dict[str, str] = {}
    current: str | None = None
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("## "):
            current = stripped[3:].strip()
            hints[current] = ""
        elif current and stripped:
            lowered = stripped.lower()
            for keyword in ("说话", "语气", "口头禅", "表达", "声音", "语速"):
                if keyword in stripped and len(hints[current]) < 120:
                    hints[current] = (hints[current] + " " + stripped).strip()
                    break
    return hints


# ---------------------------------------------------------------- analyze-voice

def _reference_files(root: Path) -> list[Path]:
    references = root / "references"
    if not references.is_dir():
        return []
    return sorted(
        p for p in references.rglob("*")
        if p.is_file() and p.suffix.lower() in (".md", ".txt")
    )


def cmd_analyze_voice(root: Path) -> None:
    files = _reference_files(root)
    if not files:
        _fail(409, "references/ 目录为空或不存在，请先导入参考小说")
        return
    anchor_texts: dict[str, list[str]] = {}
    for path in files:
        text = _read(path)
        current: str | None = None
        for line in text.splitlines():
            stripped = line.strip()
            if stripped.startswith("## "):
                current = stripped[3:].strip()
            elif current:
                quotes = _quote_texts(stripped)
                if quotes:
                    anchor_texts.setdefault(current, []).extend(quotes)
    if not anchor_texts:
        _fail(409, "参考资料中没有可识别的角色对话（请用 ## 角色名 开头，含引号对白）")
        return
    blocks: list[str] = []
    for name, quotes in sorted(anchor_texts.items()):
        joined = "\n".join(quotes)
        avg_len = round(_avg_sentence_length(joined), 1)
        q_ratio = round(_ratio(joined, QUESTION_RE), 2)
        e_ratio = round(_ratio(joined, EXCLAMATION_RE), 2)
        blocks.append(
            f"## {name}\n\n"
            f"### 核心声音定位\n"
            f"- **表达方式**: 依据参考样本归纳\n\n"
            f"### 句法指纹\n"
            f"- **平均句长**: {avg_len}\n"
            f"- **问句倾向**: {q_ratio}\n"
            f"- **叹句倾向**: {e_ratio}\n\n"
            f"### 口头禅\n"
            f"- 用词: \n\n"
            f"### 绝不使用\n"
            f"- 用词: \n\n"
            f"### 认知模式\n"
            f"- 说明: 待补充\n"
        )
    document = _VOICE_HEADING + "\n\n" + "\n".join(blocks)
    _write(root / "meta" / "character_voice.md", document)
    _json({
        "status": "success",
        "message": f"已从 {len(files)} 份参考样本提炼 {len(anchor_texts)} 个角色声音锚点",
        "character_count": len(anchor_texts),
    })


# ---------------------------------------------------------------------- scoring

_DIMENSIONS = ("声音一致性", "对话自然度", "情感真实度", "行为一致性")


def _directional_penalty(actual: float, baseline: float, up_weight: float, down_weight: float) -> float:
    """Direction-sensitive deviation penalty.

    ``actual`` above the anchor baseline (character "spikes") is treated as a
    voice-break and penalised hard; falling below the baseline (calmer than
    usual) is penalised softly because reserved/冷静 characters legitimately
    converge toward zero question/exclamation usage.
    """
    diff = actual - baseline
    return diff * up_weight if diff > 0 else -diff * down_weight


def _score_text(anchor: dict[str, Any], content: str) -> dict[str, Any]:
    sentences = _sentences(content)
    if not sentences:
        return {
            "total_score": 0,
            "grade": "F",
            "summary": "没有可评分的完整句子。",
            "detailed_scores": {d: 0 for d in _DIMENSIONS},
            "issues": [{"dimension": "对话自然度", "type": "no_content",
                        "severity": "high", "message": "内容缺少完整句子。"}],
            "recommendation": "补充完整语句后重新评估。",
        }
    avg_len = _avg_sentence_length(content)
    q_ratio = _ratio(content, QUESTION_RE)
    e_ratio = _ratio(content, EXCLAMATION_RE)

    issues: list[dict[str, str]] = []
    expected_len = anchor["avg_sentence_length"] or 14.0

    # 声音一致性：句长贴合度 + 口头禅 + 禁用词
    length_penalty = min(40, abs(avg_len - expected_len) / max(expected_len, 1.0) * 40)
    voice = 100.0 - length_penalty
    tone_hits = sum(1 for word in anchor["tone_words"] if word and word in content)
    banned_hits = [word for word in anchor["banned_words"] if word and word in content]
    voice = min(100.0, voice + min(10.0, tone_hits * 3.0))
    voice -= min(30.0, len(banned_hits) * 12.0)
    if banned_hits:
        issues.append({"dimension": "声音一致性", "type": "banned_word",
                       "severity": "high",
                       "message": f"出现了角色绝不使用的词：{'、'.join(banned_hits)}"})
    if abs(avg_len - expected_len) / max(expected_len, 1.0) > 0.5:
        issues.append({"dimension": "声音一致性", "type": "sentence_length",
                       "severity": "medium",
                       "message": f"平均句长 {avg_len:.1f} 与角色锚点 {expected_len:.1f} 偏差较大。"})

    # 对话自然度：句长方差小、节奏稳定加分；过长句子扣分
    variance = sum((len(s) - avg_len) ** 2 for s in sentences) / len(sentences)
    natural = max(0.0, 100.0 - min(40.0, variance * 0.35))
    if avg_len > 60:
        natural -= 15.0
        issues.append({"dimension": "对话自然度", "type": "long_sentence",
                       "severity": "low", "message": "存在较长句子，朗读感偏书面。"})

    # 情感真实度：语气相对角色基线的方向性一致性。
    # 向上发散（比锚点更激昂/更爱问）视为崩坏重罚；向下收敛（比锚点更平静）
    # 轻罚——冷静/寡言角色天然贴近 0，不应因"够平静"被扣分。
    # 短文本比率抖动大：用贝叶斯平滑（2 个伪计数投向基线）抑制小样本噪声。
    q_baseline = anchor["question_ratio"] or 0.15
    e_baseline = anchor["exclamation_ratio"] or 0.10
    n = len(sentences)
    prior = 2.0
    sq = (q_ratio * n + q_baseline * prior) / (n + prior)
    se = (e_ratio * n + e_baseline * prior) / (n + prior)
    emotion = 100.0 - _directional_penalty(sq, q_baseline, 220.0, 60.0) \
        - _directional_penalty(se, e_baseline, 220.0, 60.0)
    q_excess = sq - q_baseline
    e_excess = se - e_baseline
    if q_excess > 0.35 or e_excess > 0.45:
        emotion -= 8.0
        issues.append({"dimension": "情感真实度", "type": "tone_spike",
                       "severity": "medium",
                       "message": "问句/叹句密度明显高于该角色基线，情绪爆发偏突兀。"})

    # 行为一致性：风格标签命中（如"冷静"不应出现激烈用词）+ 认知模式
    behavior = 88.0
    style = anchor.get("style", "")
    if style and any(word in style for word in ("冷静", "克制", "理性", "寡言")):
        if e_ratio > 0.35:
            behavior -= 14.0
            issues.append({"dimension": "行为一致性", "type": "style_mismatch",
                           "severity": "medium",
                           "message": f"角色被定义为「{style}」，但情绪用词密度偏高。"})

    scores = {
        "声音一致性": round(max(0.0, min(100.0, voice))),
        "对话自然度": round(max(0.0, min(100.0, natural))),
        "情感真实度": round(max(0.0, min(100.0, emotion))),
        "行为一致性": round(max(0.0, min(100.0, behavior))),
    }
    total = round(sum(scores.values()) / 4)
    grade = "A" if total >= 90 else "B" if total >= 80 else "C" if total >= 70 else "D" if total >= 60 else "F"
    summary = _summary(total, issues)
    recommendation = _recommendation(scores, issues)
    return {
        "total_score": total,
        "grade": grade,
        "summary": summary,
        "detailed_scores": scores,
        "issues": issues,
        "recommendation": recommendation,
    }


def _summary(total: int, issues: list[dict[str, str]]) -> str:
    if total >= 90:
        return "角色声音表现优秀，与定义高度一致。"
    if total >= 80:
        return "整体符合角色声音定义，个别细节可微调。"
    if total >= 70:
        return "声音特征大体成立，但存在明显偏离点。"
    if issues:
        return f"声音一致性不足，存在 {len(issues)} 处偏离（{issues[0].get('message', '')}）"
    return "与角色声音锚点偏离较大，建议对照定义重写。"


def _recommendation(scores: dict[str, int], issues: list[dict[str, str]]) -> str:
    weakest = min(scores, key=scores.get)  # type: ignore[arg-type]
    parts = [f"优先提升「{weakest}」"]
    if issues:
        parts.append("；" + issues[0].get("message", ""))
    if weakest == "声音一致性":
        parts.append("。对照角色锚点的句长与口头禅逐句调整。")
    elif weakest == "对话自然度":
        parts.append("。拆分过长的书面句，让语气更口语化。")
    elif weakest == "情感真实度":
        parts.append("。对照角色基线控制问句与叹句密度，避免情绪爆发过于突兀。")
    else:
        parts.append("。注意角色设定中的情绪边界。")
    return "".join(parts)


def cmd_score_text(root: Path, character: str, content: str) -> None:
    voice_file = root / "meta" / "character_voice.md"
    if not voice_file.is_file():
        _fail(409, "character_voice.md 不存在，请先生成或保存角色声音锚点")
        return
    anchors = _parse_voice(_read(voice_file))
    if character not in anchors:
        _fail(409, f"角色「{character}」未在 character_voice.md 中定义")
        return
    result = _score_text(anchors[character], content)
    result["status"] = "success"
    result["character"] = character
    _json(result)


def cmd_score_chapter(root: Path, chapter_file: str) -> None:
    voice_file = root / "meta" / "character_voice.md"
    if not voice_file.is_file():
        _fail(409, "character_voice.md 不存在，请先生成或保存角色声音锚点")
        return
    try:
        chapter = _resolve_in(root, chapter_file)
    except ValueError:
        _fail(400, f"章节路径非法（必须位于工作区内）: {chapter_file}")
        return
    if not chapter.is_file():
        _fail(404, f"章节文件不存在: {chapter_file}")
        return
    anchors = _parse_voice(_read(voice_file))
    text = _read(chapter)
    quotes = _quote_texts(text)
    if not quotes:
        _fail(409, f"{chapter_file} 中没有可评分的对话内容（未识别到引号对白）")
        return
    # 对话归属其前最近的 ## 角色名 段落；无法归属时按默认锚点评分。
    per_character: dict[str, list[dict[str, Any]]] = {}
    for quote in quotes:
        owner = _owner_character(text, quote, anchors)
        per_character.setdefault(owner or "未知角色", []).append(
            _score_text(anchors.get(owner or "", _default_anchor()), quote)
        )
    aggregated = {
        "声音一致性": _avg_dimension(per_character, "声音一致性"),
        "对话自然度": _avg_dimension(per_character, "对话自然度"),
        "情感真实度": _avg_dimension(per_character, "情感真实度"),
        "行为一致性": _avg_dimension(per_character, "行为一致性"),
    }
    total = round(sum(aggregated.values()) / 4)
    grade = "A" if total >= 90 else "B" if total >= 80 else "C" if total >= 70 else "D" if total >= 60 else "F"
    all_issues: list[dict[str, str]] = []
    for results in per_character.values():
        for item in results:
            all_issues.extend(item["issues"])
    summary = f"共评分 {len(quotes)} 段对话；{_summary(total, all_issues[:5])}"
    _json({
        "status": "success",
        "total_score": total,
        "grade": grade,
        "summary": summary,
        "detailed_scores": {k: round(v) for k, v in aggregated.items()},
        "issues": all_issues[:20],
        "recommendation": _recommendation(aggregated, all_issues[:5]),
        "dialogues_scored": len(quotes),
    })


def _default_anchor() -> dict[str, Any]:
    return {
        "style": "", "avg_sentence_length": 14.0,
        "question_ratio": 0.15, "exclamation_ratio": 0.10,
        "tone_words": [], "banned_words": [], "cognition": "",
    }


def _owner_character(text: str, quote: str, anchors: dict[str, dict[str, Any]]) -> str | None:
    position = text.find(quote)
    if position < 0:
        return None
    prefix = text[:position]
    last_section = None
    for line in reversed(prefix.splitlines()):
        stripped = line.strip()
        if stripped.startswith("## ") and stripped[3:].strip() in anchors:
            last_section = stripped[3:].strip()
            break
    return last_section


def _avg_dimension(per_character: dict[str, list[dict[str, Any]]], dimension: str) -> float:
    values = [item["detailed_scores"][dimension] for results in per_character.values() for item in results]
    return sum(values) / len(values) if values else 0.0


def cmd_check_dialogue(root: Path, character: str, dialogue: str) -> None:
    voice_file = root / "meta" / "character_voice.md"
    if not voice_file.is_file():
        _fail(409, "character_voice.md 不存在，请先生成或保存角色声音锚点")
        return
    anchors = _parse_voice(_read(voice_file))
    if character not in anchors:
        _fail(409, f"角色「{character}」未在 character_voice.md 中定义")
        return
    anchor = anchors[character]
    banned = [word for word in anchor["banned_words"] if word and word in dialogue]
    tone_hits = [word for word in anchor["tone_words"] if word and word in dialogue]
    avg_len = _avg_sentence_length(dialogue)
    expected = anchor["avg_sentence_length"] or 14.0
    violations: list[dict[str, str]] = []
    if banned:
        violations.append({"rule": "绝不使用", "detail": f"命中禁用词：{'、'.join(banned)}"})
    if abs(avg_len - expected) / max(expected, 1.0) > 0.5 and avg_len > 0:
        violations.append({"rule": "句法指纹",
                           "detail": f"平均句长 {avg_len:.1f} 字，锚点为 {expected:.1f} 字。"})
    suggestion = "符合定义，保持。" if not violations and tone_hits else (
        "已命中口头禅，语气一致。" if not violations else "对照锚点调整句长或用词后复检。"
    )
    _json({
        "status": "success",
        "matches": not violations,
        "character": character,
        "violations": violations,
        "suggestion": suggestion,
    })


